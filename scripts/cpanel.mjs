// Post-build step for the cPanel (Apache) deployment at the domain root.
// Writes dist/.htaccess and refuses to pass a build that still looks like the GitHub Pages preview.
// Usage: npm run build:cpanel   (the GitHub Pages workflow keeps using plain `npm run build`)
import fs from 'node:fs';
import path from 'node:path';

const dist = path.resolve(process.env.OUT_DIR || 'dist');
const fail = (msg) => {
  console.error(`\n✖ cPanel build check failed: ${msg}\n`);
  process.exit(1);
};

/* ------------------------------------------------------------ .htaccess */
// Astro builds pages as files ("about.html", "tr.html" next to the "tr/" folder) and links to them
// without the extension. GitHub Pages resolves that on its own; Apache needs the rules below.
// HTTPS redirects stay commented out unless FORCE_HTTPS=true: forcing HTTPS before the SSL certificate
// is active takes the whole site down. Once AutoSSL is done, remove the "# " in cPanel's File Manager.
const forceHttps = process.env.FORCE_HTTPS === 'true';
const https = (line) => (forceHttps ? line : `# ${line}`);

// File names Apache refuses to serve. Checked below against every file in the build so it can
// never block part of the site.
const denyPattern = String.raw`(\.(env|ini|conf|config|cfg|ya?ml|toml|lock|log|sql|sqlite|db|bak|backup|old|orig|save|swp|tmp|dist|pem|key|crt|csr|p12|pfx|sh|bat|ps1|py|php\d?|ts|mjs|cjs|astro|md|map|zip|rar|7z|tar|gz|tgz|bz2|docx?|xlsx?|pptx?|psd|heic|mov)|~)$|^(package(-lock)?\.json|composer\.(json|lock)|tsconfig\.json|astro\.config\..*|readme.*|license.*|\.DS_Store|Thumbs\.db|desktop\.ini)$`;

const htaccess = `# Unique Air Cargo — generated by scripts/cpanel.mjs, do not edit on the server
Options -Indexes -MultiViews
DirectorySlash Off
DirectoryIndex index.html
ErrorDocument 404 /404.html

# Never serve files that are not part of the site, should one ever end up in public_html
# (source, config, secrets, backups, archives, office documents, logs).
<FilesMatch "(?i)${denyPattern}">
<IfModule mod_authz_core.c>
Require all denied
</IfModule>
<IfModule !mod_authz_core.c>
Order allow,deny
Deny from all
</IfModule>
</FilesMatch>

<IfModule mod_rewrite.c>
RewriteEngine On

# Hidden files and folders (.env, .git/, .htaccess …) → 403. /.well-known/ stays open for AutoSSL.
RewriteRule (^|/)\\.(?!well-known(/|$)) - [F,L]

# www → uniqueaircargo.com
RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
RewriteRule ^ ${forceHttps ? 'https' : '%{REQUEST_SCHEME}'}://%1%{REQUEST_URI} [R=301,L]

# http → https${forceHttps ? '' : ' — enable (remove "# ") once the SSL certificate is active'}
${https('RewriteCond %{HTTPS} !=on')}
${https('RewriteCond %{HTTP:X-Forwarded-Proto} !=https')}
${https('RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]')}

# /index, /index.html → /
RewriteCond %{THE_REQUEST} \\s/index(\\.html)?[\\s?]
RewriteRule ^ / [R=301,L]

# /about.html → /about (only for addresses typed or linked from outside)
RewriteCond %{THE_REQUEST} \\s/([^?\\s]+?)\\.html[\\s?]
RewriteRule ^ /%1 [R=301,L]

# /about/ → /about
RewriteCond %{REQUEST_FILENAME} !-f
RewriteRule ^(.+)/$ /$1 [R=301,L]

# /about → about.html, /tr → tr.html (checked before the "tr/" folder)
RewriteCond %{DOCUMENT_ROOT}/$1.html -f
RewriteRule ^(.+)$ /$1.html [L]
</IfModule>

<IfModule mod_mime.c>
AddType image/avif .avif
AddType image/webp .webp
AddType font/woff2 .woff2
AddType application/manifest+json .webmanifest
AddType video/mp4 .mp4
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml application/manifest+json
</IfModule>

<IfModule mod_headers.c>
# Fingerprinted build assets never change
<FilesMatch "\\.(js|css|avif|webp|jpe?g|png|svg|woff2)$">
Header set Cache-Control "public, max-age=31536000, immutable" "expr=%{REQUEST_URI} =~ m#^/_astro/#"
</FilesMatch>
<FilesMatch "\\.html$">
Header set Cache-Control "no-cache"
</FilesMatch>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "SAMEORIGIN"
</IfModule>
`;

/* --------------------------------------------------------------- Checks */
if (!fs.existsSync(path.join(dist, 'index.html'))) fail(`no build found in ${dist}`);

const robots = fs.readFileSync(path.join(dist, 'robots.txt'), 'utf8');
if (robots.includes('Disallow: /')) fail('robots.txt blocks crawlers — PUBLIC_PREVIEW is set.');

const htmlFiles = fs.readdirSync(dist, { recursive: true }).filter((f) => f.endsWith('.html')).map((f) => path.join(dist, f));
for (const file of htmlFiles) {
  const html = fs.readFileSync(file, 'utf8');
  const rel = path.relative(dist, file);
  if (/<meta name="robots" content="noindex, nofollow"/.test(html)) fail(`${rel} has the preview noindex — PUBLIC_PREVIEW is set.`);
  if (html.includes('github.io') || html.includes('/unique-air-cargo/')) fail(`${rel} still points at the GitHub Pages preview — SITE_URL/BASE_PATH are set.`);
  const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
  if (canonical && !canonical.startsWith('https://uniqueaircargo.com/')) fail(`${rel} canonical is ${canonical}`);
}

const deny = new RegExp(denyPattern, 'i');
const allFiles = fs.readdirSync(dist, { recursive: true }).filter((f) => fs.statSync(path.join(dist, f)).isFile());
const blocked = allFiles.filter((f) => f !== '.htaccess' && (deny.test(path.basename(f)) || /(^|[\\/])\./.test(f)));
// .nojekyll comes from public/ for GitHub Pages only; it is harmless and left out of the cPanel ZIP
const unexpected = blocked.filter((f) => f !== '.nojekyll');
if (unexpected.length) fail(`.htaccess would block site files: ${unexpected.slice(0, 5).join(', ')}`);

fs.writeFileSync(path.join(dist, '.htaccess'), htaccess);
console.log(`✔ cPanel build ready: ${htmlFiles.length} pages checked, .htaccess written${forceHttps ? ' (HTTPS forced)' : ' (HTTPS redirect commented out — enable after SSL)'}.`);
